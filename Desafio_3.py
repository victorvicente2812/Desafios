# Faça um programa que leia um número inteiro qualquer
# e mostre na tela a sua tabuada
# Exemplo:
# Você digitou o número : 10
# --------------- Tabuada do 10 ------------------
# 10 X 0 = 0
# 10 X 1 = 10
# E assim sucessivamente....
tabuada = int(input('Digite um número: '))

print('Você digitou o número:', tabuada)
print(tabuada, 'x 1 =', tabuada * 1)
print(tabuada, 'x 2 =', tabuada * 2)
print(tabuada, 'x 3 =', tabuada * 3)
print(tabuada, 'x 4 =', tabuada * 4)
print(tabuada, 'x 5 =', tabuada * 5)
print(tabuada, 'x 6 =', tabuada * 6)
print(tabuada, 'x 7 =', tabuada * 7)
print(tabuada, 'x 8 =', tabuada * 8)
print(tabuada, 'x 9 =', tabuada * 9)
print(tabuada, 'x 10 =', tabuada * 10)
